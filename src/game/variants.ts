// Deduplicate by `key`: the dataset import added `tripeaks`, `golf` (and
// possibly others) as fresh entries even though the curated legacy block
// already defined them. The duplicates produced React-key collisions in
// every screen that renders a `<TouchableOpacity key={v.key}>` list. We
// keep the FIRST occurrence (the curated entry, with hand-written shortDesc
// and rules) and drop subsequent re-imports silently.
export const AVAILABLE_VARIANTS = (() => {
  const seen = new Set<string>();
  return VARIANTS.filter((v) => {
    if (!v.available) return false;
    if (seen.has(v.key)) return false;
    seen.add(v.key);
    return true;
  });
})();
export const UNSUPPORTED_VARIANTS = VARIANTS.filter((v) => !v.available);
export function findVariant(key: string): Variant | undefined {
  return VARIANTS.find((v) => v.key === key);
}
